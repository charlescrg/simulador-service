-- Criar o schema dbo (simulado no H2)
CREATE SCHEMA IF NOT EXISTS dbo;

-- Usar o schema dbo
SET SCHEMA dbo;

-- Criar tabela PRODUTO
CREATE TABLE dbo.PRODUTO (
    CO_PRODUTO INT NOT NULL PRIMARY KEY,
    NO_PRODUTO VARCHAR(200) NOT NULL,
    PC_TAXA_JUROS NUMERIC(10, 9) NOT NULL,
    NU_MINIMO_MESES SMALLINT NOT NULL,
    NU_MAXIMO_MESES SMALLINT NULL,
    VR_MINIMO NUMERIC(18, 2) NOT NULL,
    VR_MAXIMO NUMERIC(18, 2) NULL
);

-- Criar tabela SIMULACAO
CREATE TABLE dbo.SIMULACAO (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    PRODUTO VARCHAR(100),
    DATA_SIMULACAO DATE,
    VALOR_SIMULADO DECIMAL(18,2),
    TEMPO_RESPOSTA_MS BIGINT,
    VALOR_TOTAL_CREDITO DECIMAL(18,2)
);

CREATE TABLE dbo.SIMULACAOTIPO (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    SIMULACAO_ID BIGINT NOT NULL,
    TIPO_SIMULACAO VARCHAR(20) NOT NULL, -- SAC ou PRICE
    VALOR_TOTAL_PARCELAS NUMERIC(18, 2) NOT NULL,
    VALOR_MEDIO_PRESTACAO NUMERIC(18, 2),
    TAXA_JURO NUMERIC(5, 4),
    PRAZO NUMERIC(18, 2),
    FOREIGN KEY (SIMULACAO_ID) REFERENCES dbo.SIMULACAO(ID)
);


