CREATE TABLE IF NOT EXISTS SIMULACAO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_PRODUTO INT,
    DATA_SIMULACAO DATE,
    PRODUTO VARCHAR(255),
    TEMPO_RESPOSTA_MS BIGINT,
    VALOR_SIMULADO DECIMAL(38,2),
    VALOR_TOTAL_CREDITO DECIMAL(38,2)
);

CREATE TABLE IF NOT EXISTS SIMULACAOTIPO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRAZO DECIMAL(38,2),
    TAXA_JURO NUMERIC(38,2),
    TIPO_SIMULACAO VARCHAR(255) NOT NULL,
    VALOR_MEDIO_PRESTACAO NUMERIC(38,2),
    VALOR_TOTAL_PARCELAS NUMERIC(38,2) NOT NULL,
    SIMULACAO_ID BIGINT NOT NULL,
    CONSTRAINT FK_SIMULACAO FOREIGN KEY (SIMULACAO_ID) REFERENCES SIMULACAO(id)
);

CREATE TABLE TELEMETRIA (
      ID BIGSERIAL PRIMARY KEY,
      DATA_REFERENCIA DATE,
      NOME_API VARCHAR(255),
      SUCESSO INTEGER,
      TEMPO_MS BIGINT
);

