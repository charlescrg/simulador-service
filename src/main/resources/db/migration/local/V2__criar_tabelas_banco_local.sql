CREATE TABLE IF NOT EXISTS SIMULACAO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODIGO_PRODUTO INT,
    DATA_SIMULACAO DATE,
    PRODUTO VARCHAR(255),
    TEMPO_RESPOSTA_MS BIGINT,
    VALOR_SIMULADO DECIMAL(38,2),
    VALOR_TOTAL_CREDITO DECIMAL(38,2)
);

CREATE TABLE IF NOT EXISTS SIMULACAOTIPO (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRAZO DECIMAL(38,2),
    TAXA_JURO DECIMAL(38,2),
    TIPO_SIMULACAO VARCHAR(255) NOT NULL,
    VALOR_MEDIO_PRESTACAO DECIMAL(38,2),
    VALOR_TOTAL_PARCELAS DECIMAL(38,2) NOT NULL,
    SIMULACAO_ID BIGINT NOT NULL,
    CONSTRAINT FK_SIMULACAO FOREIGN KEY (SIMULACAO_ID) REFERENCES SIMULACAO(id)
);

CREATE TABLE TELEMETRIA (
    id BIGSERIAL PRIMARY KEY,
    data_referencia DATE NOT NULL,
    nome_api VARCHAR(200) NOT NULL,
    qtd_requisicoes BIGINT NOT NULL,
    tempo_medio DOUBLE PRECISION,
    tempo_minimo BIGINT,
    tempo_maximo BIGINT,
    percentual_sucesso DOUBLE PRECISION
);

